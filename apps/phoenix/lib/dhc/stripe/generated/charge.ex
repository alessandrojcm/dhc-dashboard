      receipt_email: :string,
      receipt_number: :string,
      receipt_url: :string,
      refunded: :boolean,
      refunds: {Dhc.Stripe.RefundList, :t},
      review: {:union, [:string, {Dhc.Stripe.Review, :t}]},
      shipping: {Dhc.Stripe.Shipping, :t},
      source_transfer: {:union, [:string, {Dhc.Stripe.Transfer, :t}]},
      statement_descriptor: :string,
      statement_descriptor_suffix: :string,
      status: {:enum, ["failed", "pending", "succeeded"]},
      transfer: {:union, [:string, {Dhc.Stripe.Transfer, :t}]},
      transfer_data: {Dhc.Stripe.ChargeTransferData, :t},
      transfer_group: :string
    ]
  end
end

  def __fields__(type \\ :t)

  def __fields__(:t) do
    [
      amount: :integer,
      amount_captured: :integer,
      amount_refunded: :integer,
      application: {:union, [:string, {Dhc.Stripe.Application, :t}]},
      application_fee: {:union, [:string, {Dhc.Stripe.ApplicationFee, :t}]},
      application_fee_amount: :integer,
      balance_transaction: {:union, [:string, {Dhc.Stripe.BalanceTransaction, :t}]},
      billing_details: {Dhc.Stripe.BillingDetails, :t},
      calculated_statement_descriptor: :string,

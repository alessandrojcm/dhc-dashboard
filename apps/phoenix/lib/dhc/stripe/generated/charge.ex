          shipping: Dhc.Stripe.Shipping.t() | nil,
          source_transfer: Dhc.Stripe.Transfer.t() | String.t() | nil,
          statement_descriptor: String.t() | nil,
          statement_descriptor_suffix: String.t() | nil,
          status: String.t(),
          transfer: Dhc.Stripe.Transfer.t() | String.t() | nil,
          transfer_data: Dhc.Stripe.ChargeTransferData.t() | nil,
          transfer_group: String.t() | nil
        }

  defstruct [
    :amount,
    :amount_captured,
    :amount_refunded,
    :application,
    :application_fee,
